/**
 * Universal helper to render social platform icon with case-insensitive matching.
 */
export function getPlatformIcon(iconName: string, className = "w-4 h-4") {
  const icon = (iconName || "").toLowerCase().trim();

  if (icon.includes("insta") || icon === "ig") {
    return <InstagramIcon className={className} />;
  }
  if (icon.includes("git") || icon.includes("hub")) {
    return <GithubIcon className={className} />;
  }
  if (icon.includes("link") || icon.includes("in")) {
    return <LinkedinIcon className={className} />;
  }
  if (icon.includes("what") || icon.includes("wa")) {
    return <WhatsAppIcon className={className} />;
  }
  if (icon.includes("twit") || icon.includes("twitter") || icon === "x") {
    return <TwitterXIcon className={className} />;
  }
  if (icon.includes("you") || icon.includes("tube") || icon === "yt") {
    return <YoutubeIcon className={className} />;
  }
  if (icon.includes("tik") || icon.includes("tok")) {
    return <TikTokIcon className={className} />;
  }
  if (icon.includes("face") || icon.includes("book") || icon === "fb") {
    return <FacebookIcon className={className} />;
  }
  if (icon.includes("disc") || icon.includes("cord")) {
    return <DiscordIcon className={className} />;
  }
  if (icon.includes("tele") || icon.includes("gram") || icon === "tg") {
    return <TelegramIcon className={className} />;
  }
  if (icon.includes("drib")) {
    return <DribbbleIcon className={className} />;
  }
  if (icon.includes("behance") || icon.includes("be")) {
    return <BehanceIcon className={className} />;
  }
  if (icon.includes("medium") || icon.includes("med")) {
    return <MediumIcon className={className} />;
  }
  if (icon.includes("mail") || icon.includes("email") || icon.includes("surat")) {
    return <Mail className={className} />;
  }

  return <Globe className={className} />;
}
